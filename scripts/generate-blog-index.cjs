/* eslint-disable @typescript-eslint/no-require-imports -- Node CommonJS build utility. */
/* Generated card data never includes article bodies. Run before build. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const cache = new Map();
function loadTs(file) {
  const full = path.resolve(file);
  if (cache.has(full)) return cache.get(full).exports;
  const mod = { exports: {} };
  cache.set(full, mod);
  const source = fs.readFileSync(full, 'utf8');
  const compiled = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
    fileName: full,
  }).outputText;
  vm.runInNewContext(compiled, {
    exports: mod.exports,
    require(id) {
      if (!id.startsWith('.')) throw new Error('Unexpected dependency in blog data: ' + id);
      return loadTs(path.resolve(path.dirname(full), id + '.ts'));
    },
  }, { filename: full });
  return mod.exports;
}

const sourceFile = path.join(root, 'src/lib/blog-data.ts');
const { blogPosts } = loadTs(sourceFile);
const summaries = blogPosts.map((post) => Object.fromEntries(
  Object.entries(post).filter(([key]) => key !== 'content' && key !== 'contentEn')
));
if (new Set(summaries.map((post) => post.slug)).size !== summaries.length) {
  throw new Error('Duplicate blog slug');
}
const source = fs.readFileSync(sourceFile, 'utf8');
const start = source.indexOf('const STOP_WORDS');
if (start < 0) throw new Error('Related-article algorithm not found');
const related = source.slice(start).replace(/\bBlogPost\b/g, 'BlogPostSummary').replace(/\bblogPosts\b/g, 'blogSummaries');
const output = '// Generated by scripts/generate-blog-index.cjs. Do not edit by hand.\n'
  + "import type { BlogPost } from './blog-data';\n\n"
  + 'export type BlogPostSummary = Omit<BlogPost, "content" | "contentEn">;\n\n'
  + 'export const blogSummaries: BlogPostSummary[] = ' + JSON.stringify(summaries, null, 2) + ';\n\n'
  + related;
const destination = path.join(root, 'src/lib/blog-index.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
    console.error('Blog index is stale. Run npm run blog:index.');
    process.exitCode = 1;
  } else console.log('Blog index matches ' + summaries.length + ' articles; no bodies included.');
} else {
  fs.writeFileSync(destination, output);
  console.log('Generated summaries for ' + summaries.length + ' articles.');
}
